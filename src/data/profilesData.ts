export function findProfileByVidPid(vid: string, pid: string): ControllerProfile | undefined {
  const cleanVid = vid.replace('0x', '').toUpperCase().padStart(4, '0');
  const cleanPid = pid.replace('0x', '').toUpperCase().padStart(4, '0');
  return CONTROLLER_PROFILES.find(
    (p) => p.vendorId.toUpperCase() === cleanVid && p.productId.toUpperCase() === cleanPid
  );
}
